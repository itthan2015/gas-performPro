create or replace function pformpro_emp_resign_default() returns trigger language plpgsql as $$
begin
  if new.active = false and (tg_op = 'INSERT' or old.active is distinct from false) then
    new.evaluate := false;
    if new.emp_status is null or new.emp_status = 'working' then new.emp_status := 'resigned'; end if;
  elsif new.active = true and tg_op = 'UPDATE' and old.active = false and new.emp_status = 'resigned' then
    new.emp_status := 'working';
  end if;
  return new;
end $$;
